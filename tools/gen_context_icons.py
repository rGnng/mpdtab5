#!/usr/bin/env python3
"""Rasterize vendored context SVGs as recolorable 32px LVGL A8 images.

Requires CairoSVG 2.8.2 and Pillow 12.0.0. Preserves source opacity.
"""
from io import BytesIO
from pathlib import Path

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 32


def main():
    out = ['/* Generated by tools/gen_context_icons.py. See assets/icons/README.md. */',
           '#ifndef MPDTAB5_CONTEXT_ICONS_H', '#define MPDTAB5_CONTEXT_ICONS_H',
           '#include "lvgl.h"', '']
    for name, symbol in [('list-arrow-to-bottom-expressive', 'context_add_to_queue'),
                         ('list-arrow-to-top-expressive', 'context_play_next')]:
        png = cairosvg.svg2png(url=str(ROOT / 'assets/icons' / (name + '.svg')),
                              output_width=SIZE, output_height=SIZE)
        alpha = Image.open(BytesIO(png)).convert('RGBA').getchannel('A').tobytes()
        out.append(f'static const uint8_t {symbol}_data[] = {{')
        out.extend('    ' + ', '.join(f'0x{x:02x}' for x in alpha[i:i+20]) + ','
                   for i in range(0, len(alpha), 20))
        out.extend(['};', f'static const lv_image_dsc_t {symbol} = {{',
                    '    .header.magic = LV_IMAGE_HEADER_MAGIC,',
                    '    .header.cf = LV_COLOR_FORMAT_A8,',
                    f'    .header.w = {SIZE}, .header.h = {SIZE}, .header.stride = {SIZE},',
                    f'    .data_size = sizeof({symbol}_data), .data = {symbol}_data,',
                    '};', ''])
    out.append('#endif /* MPDTAB5_CONTEXT_ICONS_H */')
    (ROOT / 'app/ui/context_icons.h').write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
