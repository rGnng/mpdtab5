#!/usr/bin/env python3
"""Generate constant raw-volume targets for the four supported control scales."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
out=['#pragma once\n// Generated by tools/gen_volume_scales.py; shared with ColoPlay.\n']
for mode,count in [(16,16),(64,64),(2,50),(5,20)]:
 values=[]
 for i in range(count+1):
  value=(i/count)**2 if mode in (16,64) else i/count
  literal=format(value,'.10g')
  if '.' not in literal and 'e' not in literal:literal+='.0'
  values.append(literal+'f')
 out.append(f'static const float volume_scale_{mode}[{count+1}]={{\n')
 for at in range(0,len(values),8):out.append('    '+','.join(values[at:at+8])+',\n')
 out.append('};\n')
(root/'app/backend/volume_scale_tables.h').write_text(''.join(out))
print('Generated 154 targets (616 bytes)')
